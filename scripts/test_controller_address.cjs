const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {loadComponentRegistry}=require('../devserver/component-registry');
const context={};
const registry=loadComponentRegistry(context);
const source=fs.readFileSync('data/app.js','utf8');
vm.runInContext(source.slice(source.indexOf('function updatePreviewControllerAddress('),source.indexOf('function commitPreviewComponentName(')),context);
const board={objectType:'PCA9685 Servo Controller',i2cAddress:64};
const servo={objectType:'Servo',address:'0x40',channel:0};
const other={objectType:'Servo',address:'0x42',channel:1};
context.servoPreview={nodes:[board],configuration:{components:[board,servo,other],servoController:{address:'0x40'}}};
context.updatePreviewControllerAddress(board,65);
assert.equal(board.i2cAddress,65);
assert.equal(servo.address,'0x41','boot configuration must use the new address');
assert.equal(other.address,'0x42');
assert.equal(context.servoPreview.configuration.servoController.address,'0x41');
assert.equal(registry.settings({objectType:board.objectType}).i2cAddress,64);
assert.throws(()=>registry.settings({...board,i2cAddress:64.5}),/integer/);
other.channel=0;
assert.throws(()=>context.updatePreviewControllerAddress(board,66),/same controller channel/);
assert.equal(servo.address,'0x41','failed changes must be atomic');
assert.equal(board.i2cAddress,65);
console.log('Controller address checks passed: default, saved servo boot address, unrelated outputs and collision protection.');
