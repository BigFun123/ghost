const assert = require('node:assert/strict');
const fs = require('node:fs'), vm = require('node:vm');
const context = { GhostSensor:require('../data/simulated-sensor'), componentRegistry: { register() {} }, document: { createElement: () => ({ classList: { toggle() {} }, setAttribute() {}, addEventListener(event, fn) { this[event] = fn; }, append(...children) { this.children = [...(this.children ?? []), ...children]; } }) } };
vm.createContext(context);
vm.runInContext(fs.readFileSync('data/components/VL53L0X.js', 'utf8'), context);
let settingsOpened = 0;
const panel = context.createVL53L0XPanel({ openSettings: () => settingsOpened++ });
const value = panel.element.children[2], caption = panel.element.children[3];
const scene = { node: { name: 'Front distance' }, nodes: [], index: 0, surfaces: [], offline: true,
 worldPoint: (_, i, point) => point, measureSensor: () => ({ origin:[0,2,3.1], direction:[0,0,1], valid:true, distanceMm:123.45, hit:{name:"Test surface"} }) };
panel.update(scene); assert.equal(value.textContent, '123.5 mm');
panel.update({ ...scene, measureSensor: () => ({origin:[0,2,3.1],direction:[0,0,1],valid:false,distanceMm:null,hit:null}) }); assert.equal(value.textContent, 'No hit');
const live = { ...scene, offline: false, telemetryAgeMs: 0, sensors: { vl53l0x: { ready: true, valid: true, distanceMm: 456 } } };
panel.update(live); assert.equal(value.textContent, '456 mm'); assert.match(caption.textContent, /Physical/);
panel.update({ ...live, telemetryAgeMs: 3001 }); assert.equal(value.textContent, 'Stale reading');
panel.update({ ...live, sensors: null }); assert.equal(value.textContent, 'Waiting for sensor');
for (const distanceMm of [null, NaN]) { panel.update({ ...live, sensors: { vl53l0x: { ready: true, valid: true, distanceMm } } }); assert.equal(value.textContent, 'Invalid reading'); }
panel.update({ ...live, sensors: { vl53l0x: { ready: false } } }); assert.equal(value.textContent, 'Unavailable');
panel.update(scene); assert.equal(value.textContent, '123.5 mm'); assert.match(caption.textContent, /Simulated/);
console.log('Distance panel passed: offline ray, no hit, physical readings, missing/invalid/stale data, mode switching.');

const [draw] = panel.element.children[4].children;
const config = panel.element.children[7], clear = panel.element.children[8];
config.click(); assert.equal(settingsOpened, 1);
assert.equal(panel.element.children[4].children.length, 1);
draw.click();
for (let i = 0; i < 2005; i++) panel.update({ ...live, sensors: { vl53l0x: { ready: true, valid: true, distanceMm: i } } });
const scan = context.vl53l0xScan(scene.node);
assert.equal(scan.points.length, 2000);
assert.equal(scan.points[0][2], 8.1);
assert.equal(scan.points.at(-1)[2], 2007.1);
draw.click(); panel.update(live); assert.equal(scan.points.length, 2000);
clear.click(); assert.equal(scan.points.length, 0);
console.log('Scan capture passed: world endpoints, 2000-point FIFO, pause and clear.');
scene.node.distanceMultiplier=1.25;
panel.update(live);assert.equal(value.textContent,'570 mm','live panel uses calibrated distance');
panel.update(scene);assert.equal(value.textContent,'123.5 mm','simulation keeps geometric distance');
draw.click();
panel.update({...live,sensors:{vl53l0x:{ready:true,valid:true,distanceMm:100}}});
assert.equal(scan.points.at(-1)[2],128.1,'captured points use calibrated distance');
const host={append(group){this.group=group;}};
let changed=0;
context.renderVL53L0XSettings({node:scene.node,host,editing:true,change(){changed++;}});
const input=host.group.children[0].children[0].children[0];
input.setCustomValidity=function(message){this.error=message;};input.reportValidity=()=>{};
input.value='2';input.change();
assert.equal(scene.node.distanceMultiplier,2);assert.equal(changed,1);assert.equal(scan.points.length,0);
for(const invalid of ['', '0','-1','NaN','1001']) {
  input.value=invalid;input.change();assert.equal(scene.node.distanceMultiplier,2);assert.equal(changed,1);
}
console.log('Distance calibration passed: settings validation, panel, beam capture and simulation isolation.');

let calibration={offline:false,sensor:{ready:true,valid:true,distanceMm:100},telemetryAgeMs:0,direction:[0,-1,0],simulated:{valid:true,distanceMm:300}};
context.renderVL53L0XSettings({node:scene.node,host,editing:true,change(){},readCalibration:()=>calibration});
const buttons=host.group.children[0].children;
buttons[1].click();
assert.equal(scene.node.calibrationGain1,1.5);
calibration={...calibration,direction:[0,-0.5,Math.sqrt(0.75)],simulated:{valid:true,distanceMm:600}};
buttons[2].click();
assert.equal(scene.node.calibrationGain2,3);
const sensor=calibration.sensor;
assert(Math.abs(context.vl53l0xDistance(scene.node,sensor,0,[0,-1,0])-300)<1e-8);
assert(Math.abs(context.vl53l0xDistance(scene.node,sensor,0,calibration.direction)-600)<1e-8);
assert(Math.abs(context.vl53l0xDistance(scene.node,sensor,0,[0,-Math.sin(Math.PI/3),0.5])-450)<1e-8);
assert.equal(context.vl53l0xDistance(scene.node,sensor,4000,calibration.direction),null);
buttons[3].click();
assert.equal(context.vl53l0xDistance(scene.node,sensor,0,calibration.direction),200);
console.log('Simulation calibration passed: capture, angle-dependent range, interpolation, stale reading rejection and reset.');
const mixerCalibration=panel.element.children[9];
panel.update({...live,measureSensor:()=>({valid:true,distanceMm:400})});
mixerCalibration.children[0].click();
assert(scene.node.calibrationGain1>0,'mixer captures calibration on the same node as Setup');
assert(mixerCalibration.children[3].textContent.includes('Angle 1 captured'));
mixerCalibration.children[2].click();
assert.equal(scene.node.calibrationGain1,0);
assert.equal(scene.node.calibrationGain2,0);
console.log('Mixer calibration buttons passed: capture, shared settings and reset.');
