const assert = require('node:assert/strict');
const fs = require('node:fs'), vm = require('node:vm');
const {loadComponentRegistry} = require('../devserver/component-registry');
const context = {};
const registry = loadComponentRegistry(context);
const app = fs.readFileSync('data/app.js','utf8');
vm.runInContext(app.slice(app.indexOf('function rotateServoPoint('),app.indexOf('function previewWorldPoint(')),context);
const parent={objectType:'Servo',parent:null,angle:90,position:[0,1000,0],rotation:[0,0,0]};
const node={name:'IMU',objectType:'GY-801',parent:1,position:[0,0,0],rotation:[0,0,0]};
let nodes=[parent,node];
const read = now => registry.metrics({nodes,worldPoint:context.servoWorldPoint,now});
const value=(series,id)=>series.find(trace=>trace.id===id).value;
const near=(actual,expected)=>assert(Math.abs(actual-expected)<1e-5, `${actual} != ${expected}`);
let output=read(0);
assert.equal(output.length,16);
assert(output.every(trace=>trace.owner===node&&trace.name.includes('(sim)')));
near(value(output,'altitude'),1);
near(value(output,'magX'),0);near(value(output,'magY'),-20);near(value(output,'magZ'),40);
near(value(output,'heading'),0);near(value(output,'temperature'),14.9935);
for(const axis of ['X','Y','Z'])for(const sensor of ['gyro','accel','mag'])assert(output.some(trace=>trace.id===sensor+axis));
assert(value(output,'pressure')<1013.25);
assert.equal(value(output,'gyroY'),null);
read(100);output=read(200);
near(value(output,'gyroY'),0);near(value(output,'accelY'),9.80665);near(value(output,'accelX'),0);
parent.rotation[1]=9;output=read(300);
near(value(output,'gyroY'),90);near(value(output,'rotationY'),9);
near(value(output,'heading'),9);
near(Math.hypot(value(output,'magX'),value(output,'magY'),value(output,'magZ')),Math.hypot(0,-20,40));
assert(value(output,'magX')<0,'magnetic vector follows the rotated board');
parent.rotation[1]=18;output=read(400);near(value(output,'gyroY'),90);
output=read(2000);assert.equal(value(output,'gyroY'),null);assert.equal(value(output,'accelY'),null);
nodes=[parent,node];output=read(2100);assert.equal(value(output,'gyroY'),null,'reloaded assembly resets derivative history');
// Gravity rotates into the sensor frame, rather than using global axes.
parent.rotation[1]=0;node.rotation=[90,0,0];read(2200);output=read(2300);
near(value(output,'accelZ'),-9.80665);
near(value(output,'magY'),40);near(value(output,'magZ'),20);
assert.equal(value(output,'heading'),null,'vertical compass forward axis has no horizontal heading');
node.rotation=[0,0,0];parent.rotation=[0,-1,0];output=read(2400);near(value(output,'heading'),359);
parent.rotation=[0,1,0];output=read(2500);near(value(output,'heading'),1);
parent.position[1]=0;output=read(2600);near(value(output,'temperature'),15);near(value(output,'pressure'),1013.25);
parent.position[1]=1000;output=read(2700);assert(value(output,'temperature')<15);assert(value(output,'pressure')<1013.25);
console.log('GY-801 metrics passed: stationary gravity, parent rotation, angular velocity, altitude/pressure, simulation labels and history reset.');
